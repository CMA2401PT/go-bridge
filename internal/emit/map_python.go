package emit

import (
	"fmt"
	"go-bridge/internal/pyapi"
	"strings"
)

func stubMap(b *strings.Builder, t *pyapi.Type) {
	input := "items: _typing.Iterable[_builtins.tuple[" + annotation(t.Key) + ", " + annotation(t.Elem) + "]] = ()"
	if t.Underlying != nil {
		input = "value: " + annotation(t.Underlying)
	}
	fmt.Fprintf(b, `    def __new__(_cls, %s) -> _typing.Self: ...
    def __init__(_self, %s) -> None: ...
    @_builtins.classmethod
    def nil(cls) -> _typing.Self: ...
    @_builtins.property
    def is_nil(self) -> _builtins.bool: ...
    __iter__: _typing.ClassVar[None]
    def __len__(self) -> _builtins.int: ...
    def __getitem__(self, key: %s) -> %s: ...
    def __setitem__(self, key: %s, value: %s) -> None: ...
    def __contains__(self, key: %s) -> _builtins.bool: ...
    def delete(self, key: %s) -> None: ...
    def clear(self) -> None: ...
    def clone(self) -> _typing.Self: ...
    def copy_to_py_items(self) -> _builtins.list[_builtins.tuple[%s, %s]]: ...
`, input, input, annotation(t.Key), annotation(t.Elem), annotation(t.Key), annotation(t.Elem), annotation(t.Key), annotation(t.Key), annotation(t.Key), annotation(t.Elem))
}
