// Package emit renders validated Python and ABI plans. It does not inspect ASTs.
package emit

import (
	"bytes"
	_ "embed"
	"encoding/json"
	"fmt"
	"go/format"
	"path/filepath"
	"strings"

	"go-bridge/internal/abi"
	"go-bridge/internal/pyapi"
)

//go:embed runtime.cpp.tmpl
var cppRuntime string

//go:embed build.py
var buildScript string

func Files(p *abi.Package) (map[string][]byte, error) {
	g, err := format.Source([]byte(goSource(p)))
	if err != nil {
		return nil, fmt.Errorf("format generated Go: %w", err)
	}
	config, err := json.MarshalIndent(struct {
		SourceDir  string `json:"source_dir"`
		Package    string `json:"package"`
		ImportPath string `json:"import_path"`
	}{p.Python.Go.Dir, p.Python.Name, p.Python.Go.Path}, "", "  ")
	if err != nil {
		return nil, err
	}
	return map[string][]byte{
		"go/main.go":   g,
		"bindings.cpp": []byte(cppSource(p)),
		filepath.Join(p.Python.Name, "__init__.pyi"): []byte(stub(p.Python)),
		filepath.Join(p.Python.Name, "__init__.py"):  []byte(pythonSource(p.Python)),
		filepath.Join(p.Python.Name, "py.typed"):     {},
		"build.py":                                   []byte(buildScript),
		"bridge.json":                                append(config, '\n'),
		"README.md":                                  []byte(fmt.Sprintf("# %s\n\nGenerated from `%s`. Requires the original Go source tree.\n\nBuild with `python build.py` (pybind11 and setuptools required).\nImport from `.build/python` using that same interpreter.\nThe adapter and extension are a matched pair; regenerate and rebuild together.\n", p.Python.Name, p.Python.Go.Path)),
	}, nil
}

func goSource(p *abi.Package) string {
	var b strings.Builder
	b.WriteString("// Code generated by go-bridge. DO NOT EDIT.\npackage main\n/*\n#include <stdint.h>\n#include <stddef.h>\n#include <stdlib.h>\ntypedef struct { char *data; size_t size; } SBString;\n")
	for _, op := range p.Operations {
		b.WriteString("typedef struct {\nuint8_t panicked;\nSBString panic_message;\n")
		for i, r := range op.Results {
			fmt.Fprintf(&b, "%s r%d;\n", r.C, i)
		}
		fmt.Fprintf(&b, "} %s;\n", op.Result)
	}
	b.WriteString("*/\nimport \"C\"\nimport (\n\"fmt\"\n\"unsafe\"\n")
	alias := "api"
	if len(p.Operations) == 0 {
		alias = "_"
	}
	fmt.Fprintf(&b, "%s %q\n)\n", alias, p.Python.Go.Path)
	b.WriteString(`
func bridgeString(value string) C.SBString {
    return C.SBString{data: C.CString(value), size: C.size_t(len(value))}
}
func bridgeInput(value C.SBString) string {
    return string(unsafe.Slice((*byte)(unsafe.Pointer(value.data)), int(value.size)))
}
// Also used when the target has no functions, keeping the runtime self-contained.
var _ = fmt.Sprint
`)
	for _, op := range p.Operations {
		fmt.Fprintf(&b, "\n//export %s\nfunc %s(", op.Symbol, op.Symbol)
		for i, a := range op.Params {
			if i != 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "a%d C.%s", i, a.C)
		}
		fmt.Fprintf(&b, ") (out C.%s) {\ncomplete := false\ndefer func() {\nif !complete {\nreason := recover()\n", op.Result)
		// Release any already converted results before handing back the panic.
		for i, r := range op.Results {
			if r.Kind == abi.String {
				fmt.Fprintf(&b, "C.free(unsafe.Pointer(out.r%d.data))\nout.r%d = C.SBString{}\n", i, i)
			}
		}
		b.WriteString("out.panicked = 1\nout.panic_message = bridgeString(fmt.Sprint(reason))\n}\n}()\n")
		if len(op.Results) > 0 {
			for i := range op.Results {
				if i != 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(&b, "r%d", i)
			}
			b.WriteString(" := ")
		}
		fmt.Fprintf(&b, "api.%s(", op.Python.Go.Name)
		for i, a := range op.Params {
			if i != 0 {
				b.WriteString(", ")
			}
			x := fmt.Sprintf("a%d", i)
			switch a.Kind {
			case abi.String:
				fmt.Fprintf(&b, "bridgeInput(%s)", x)
			case abi.Boolean:
				fmt.Fprintf(&b, "%s != 0", x)
			default:
				fmt.Fprintf(&b, "%s(%s)", a.Go, x)
			}
		}
		b.WriteString(")\n")
		for i, r := range op.Results {
			switch r.Kind {
			case abi.String:
				fmt.Fprintf(&b, "out.r%d = bridgeString(r%d)\n", i, i)
			case abi.Boolean:
				fmt.Fprintf(&b, "if r%d { out.r%d = 1 }\n", i, i)
			default:
				fmt.Fprintf(&b, "out.r%d = C.%s(r%d)\n", i, r.C, i)
			}
		}
		b.WriteString("complete = true\nreturn\n}\n")
	}
	b.WriteString("\nfunc main() {}\n")
	return b.String()
}

func cppSource(p *abi.Package) string {
	var b strings.Builder
	b.WriteString("// Code generated by go-bridge. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "#include %q\n", "libbridge_"+p.Python.Name+".h")
	b.WriteString(cppRuntime)
	fmt.Fprintf(&b, "\nstatic_assert(sizeof(intptr_t) * 8 == %d, \"regenerate for this target architecture\");\n", p.IntBits)
	for _, op := range p.Operations {
		fmt.Fprintf(&b, "struct Owned%s {\n%s data;\n~Owned%s() {\nstd::free(data.panic_message.data);\n", op.Result, op.Result, op.Result)
		for i, r := range op.Results {
			if r.Kind == abi.String {
				fmt.Fprintf(&b, "std::free(data.r%d.data);\n", i)
			}
		}
		b.WriteString("}\n};\n")
	}
	b.WriteString("\nPYBIND11_MODULE(_native, module) {\nmodule.doc() = \"Generated Go bindings\";\nauto panic_type = py::reinterpret_steal<py::object>(PyErr_NewException(\"")
	b.WriteString(p.Python.Name)
	b.WriteString("._native.GoPanic\", PyExc_RuntimeError, nullptr));\nif (!panic_type) throw py::error_already_set();\nmodule.attr(\"GoPanic\") = panic_type;\n")
	for _, op := range p.Operations {
		fmt.Fprintf(&b, "module.def(%q, [panic_type](", op.Python.Name)
		for i := range op.Params {
			if i != 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "py::handle a%d", i)
		}
		b.WriteString(") -> py::object {\n")
		for i, a := range op.Params {
			convert := ""
			switch a.Kind {
			case abi.String:
				convert = "string_arg"
			case abi.Boolean:
				convert = "bool_arg"
			case abi.Float:
				convert = "float_arg<" + a.C + ">"
			default:
				convert = "integer_arg<" + a.C + ">"
			}
			fmt.Fprintf(&b, "const auto v%d = %s(a%d);\n", i, convert, i)
		}
		fmt.Fprintf(&b, "Owned%s owned{%s(", op.Result, op.Symbol)
		for i := range op.Params {
			if i != 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "v%d", i)
		}
		b.WriteString(")};\nconst auto& result = owned.data;\nif (result.panicked) {\nauto message = decode(result.panic_message, \"replace\");\nPyErr_SetObject(panic_type.ptr(), message.ptr());\nthrow py::error_already_set();\n}\n")
		if len(op.Results) > 1 {
			fmt.Fprintf(&b, "py::tuple output(%d);\n", len(op.Results))
		}
		for i, r := range op.Results {
			if len(op.Results) == 1 {
				b.WriteString("return ")
			} else {
				fmt.Fprintf(&b, "output[%d] = ", i)
			}
			switch r.Kind {
			case abi.String:
				fmt.Fprintf(&b, "decode(result.r%d, \"strict\")", i)
			case abi.Boolean:
				fmt.Fprintf(&b, "py::bool_(result.r%d != 0)", i)
			case abi.Float:
				fmt.Fprintf(&b, "py::float_(result.r%d)", i)
			default:
				fmt.Fprintf(&b, "py::int_(result.r%d)", i)
			}
			b.WriteString(";\n")
		}
		if len(op.Results) == 0 {
			b.WriteString("return py::none();\n")
		}
		if len(op.Results) > 1 {
			b.WriteString("return output;\n")
		}
		b.WriteString("}")
		for _, arg := range op.Python.Params {
			fmt.Fprintf(&b, ", py::arg(%q)", arg.Name)
		}
		b.WriteString(");\n")
	}
	b.WriteString("}\n")
	return b.String()
}

func returnType(f *pyapi.Function) string {
	switch len(f.Results) {
	case 0:
		return "None"
	case 1:
		return "_builtins." + f.Results[0].Name
	default:
		names := make([]string, len(f.Results))
		for i, r := range f.Results {
			names[i] = "_builtins." + r.Name
		}
		return "_builtins.tuple[" + strings.Join(names, ", ") + "]"
	}
}

func stub(p *pyapi.Package) string {
	var b strings.Builder
	b.WriteString("# Code generated by go-bridge. DO NOT EDIT.\nimport builtins as _builtins\n\nclass GoPanic(_builtins.RuntimeError): ...\n\n")
	for _, a := range p.Aliases {
		fmt.Fprintf(&b, "%s = _builtins.%s\n", a.Name, a.Type.Name)
	}
	for _, f := range p.Functions {
		fmt.Fprintf(&b, "def %s(", f.Name)
		for i, a := range f.Params {
			if i != 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%s: _builtins.%s", a.Name, a.Type.Name)
		}
		fmt.Fprintf(&b, ") -> %s: ...\n", returnType(f))
	}
	return b.String()
}

func pythonSource(p *pyapi.Package) string {
	var b bytes.Buffer
	b.WriteString("# Code generated by go-bridge. DO NOT EDIT.\nimport builtins as _builtins\nfrom ._native import GoPanic as GoPanic\n")
	names := []string{"GoPanic"}
	for _, f := range p.Functions {
		fmt.Fprintf(&b, "from ._native import %s as %s\n", f.Name, f.Name)
		names = append(names, f.Name)
	}
	for _, a := range p.Aliases {
		fmt.Fprintf(&b, "%s = _builtins.%s\n", a.Name, a.Type.Name)
		names = append(names, a.Name)
	}
	encoded, _ := json.Marshal(names)
	fmt.Fprintf(&b, "\n__all__ = %s\n", encoded)
	return b.String()
}
