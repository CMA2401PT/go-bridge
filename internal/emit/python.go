package emit

import (
	"encoding/json"
	"fmt"
	"strings"

	"go-bridge/internal/gomodel"
	"go-bridge/internal/pyapi"
)

// Generated Python refers to builtins as _builtins.X, because a public
// function may legitimately be named int, str or tuple after snake_case.
const builtins = "_builtins."

// stubSource renders __init__.pyi.
func stubSource(p *pyapi.Package) string {
	var b strings.Builder
	b.WriteString("# Code generated by go-bridge. DO NOT EDIT.\nfrom __future__ import annotations\nimport builtins as _builtins\nimport typing as _typing\n\n")
	stubClasses(&b, p)
	for _, c := range p.AnyConversions {
		if c.Type.Shape == pyapi.Builtin {
			fmt.Fprintf(&b, "def %[1]s(value: %[4]s) -> %[5]s: ...\ndef %[2]s(value: %[5]s) -> %[4]s: ...\ndef %[3]s(value: %[5]s) -> %[4]s | None: ...\n", c.Box, c.Assert, c.TryAssert, annotation(c.Type), p.Any.Name)
		}
	}
	for _, a := range p.Aliases {
		fmt.Fprintf(&b, "%s = %s\n", a.Name, annotation(a.Type))
	}
	for _, f := range p.Functions {
		params := join(len(f.Params), func(i int) string {
			return f.Params[i].Name + ": " + annotation(f.Params[i].Type)
		})
		fmt.Fprintf(&b, "def %s(%s) -> %s: ...\n", f.Name, params, returnAnnotation(f))
	}
	return b.String()
}

func returnAnnotation(f *pyapi.Function) string {
	switch len(f.Results) {
	case 0:
		return "None"
	case 1:
		return annotation(f.Results[0])
	default:
		return builtins + "tuple[" + join(len(f.Results), func(i int) string { return annotation(f.Results[i]) }) + "]"
	}
}

// pythonSource renders __init__.py, which re-exports the native module.
func pythonSource(p *pyapi.Package) string {
	var b strings.Builder
	// Always load the extension, even for alias-only packages, preserving the
	// target Go package's init behavior without inventing a public export.
	b.WriteString("# Code generated by go-bridge. DO NOT EDIT.\nimport builtins as _builtins\nfrom . import _native\n")
	exports := []string{}
	if hasRefs(p) {
		for _, name := range []string{"Ref", "Slice", "Ptr"} {
			fmt.Fprintf(&b, "from ._native import %s as %s\n", name, name)
			exports = append(exports, name)
		}
	}
	for _, t := range p.Types {
		if t.Shape != pyapi.Builtin {
			fmt.Fprintf(&b, "from ._native import %s as %s\n", t.Name, t.Name)
			exports = append(exports, t.Name)
		}
	}
	for _, f := range p.Functions {
		fmt.Fprintf(&b, "from ._native import %s as %s\n", f.Name, f.Name)
		exports = append(exports, f.Name)
	}
	for _, c := range p.AnyConversions {
		if c.Type.Shape == pyapi.Builtin {
			for _, name := range []string{c.Box, c.Assert, c.TryAssert} {
				fmt.Fprintf(&b, "from ._native import %s as %s\n", name, name)
				exports = append(exports, name)
			}
		}
	}
	for _, a := range p.Aliases {
		fmt.Fprintf(&b, "%s = %s\n", a.Name, annotation(a.Type))
		exports = append(exports, a.Name)
	}
	// Names are plain identifiers, so a JSON list is also a Python literal.
	encoded, _ := json.Marshal(exports)
	fmt.Fprintf(&b, "\n__all__ = %s\n", encoded)
	return b.String()
}

func annotation(t *pyapi.Type) string {
	if t.Go.Kind == gomodel.Basic {
		return builtins + t.Name
	}
	return t.Name
}

func hasRefs(p *pyapi.Package) bool {
	for _, t := range p.Types {
		if t.Shape != pyapi.Builtin && t.Shape != pyapi.NamedValue {
			return true
		}
	}
	return false
}
