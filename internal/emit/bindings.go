package emit

import (
	"fmt"
	"strings"

	"go-bridge/internal/abi"
)

// cppSource renders the pybind11 module that calls the cgo exports.
func cppSource(p *abi.Package) string {
	var b strings.Builder
	b.WriteString("// Code generated by go-bridge. DO NOT EDIT.\n")
	// The header is written by `go build -buildmode=c-shared` next to the library.
	fmt.Fprintf(&b, "#include %q\n", "libbridge_"+p.Python.Name+".h")
	b.WriteString(cppRuntime)
	fmt.Fprintf(&b, "\nstatic_assert(sizeof(intptr_t) * 8 == %d, \"regenerate for this target architecture\");\n", p.IntBits)
	for _, op := range p.Operations {
		if len(op.Results) > 0 {
			cppOwner(&b, op)
		}
	}
	b.WriteString(`
PYBIND11_MODULE(_native, module) {
module.doc() = "Generated Go bindings";
`)
	fmt.Fprintf(&b, "%s();\n", abi.InitSymbol)
	for _, op := range p.Operations {
		cppFunction(&b, op)
	}
	b.WriteString("}\n")
	return b.String()
}

// cppOwner renders an RAII holder that frees every buffer a result owns, so
// normal returns and Python conversion errors both release memory. An
// unrecovered Go panic terminates the process before ownership reaches C++.
func cppOwner(b *strings.Builder, op *abi.Operation) {
	fmt.Fprintf(b, "struct Owned%s {\n%s data;\n~Owned%s() {\n", op.Result, op.Result, op.Result)
	for i, r := range op.Results {
		if r.Kind == abi.String {
			fmt.Fprintf(b, "std::free(data.r%d.data);\n", i)
		}
	}
	b.WriteString("}\n};\n")
}

// cppFunction registers one operation. Arguments are converted strictly
// before the call; results are owned before any Python object is created.
func cppFunction(b *strings.Builder, op *abi.Operation) {
	params := join(len(op.Params), func(i int) string { return fmt.Sprintf("py::handle a%d", i) })
	fmt.Fprintf(b, "module.def(%q, [](%s) -> py::object {\n", op.Python.Name, params)
	for i, a := range op.Params {
		fmt.Fprintf(b, "const auto v%d = %s(a%d);\n", i, cppInput(a), i)
	}
	args := join(len(op.Params), func(i int) string { return fmt.Sprintf("v%d", i) })
	if len(op.Results) == 0 {
		fmt.Fprintf(b, "%s(%s);\n", op.Symbol, args)
	} else {
		fmt.Fprintf(b, "Owned%s owned{%s(%s)};\nconst auto& result = owned.data;\n", op.Result, op.Symbol, args)
	}
	switch len(op.Results) {
	case 0:
		b.WriteString("return py::none();\n")
	case 1:
		fmt.Fprintf(b, "return %s;\n", cppOutput(op.Results[0], "result.r0"))
	default:
		fmt.Fprintf(b, "py::tuple output(%d);\n", len(op.Results))
		for i, r := range op.Results {
			fmt.Fprintf(b, "output[%d] = %s;\n", i, cppOutput(r, fmt.Sprintf("result.r%d", i)))
		}
		b.WriteString("return output;\n")
	}
	b.WriteString("}")
	for _, arg := range op.Python.Params {
		fmt.Fprintf(b, ", py::arg(%q)", arg.Name)
	}
	b.WriteString(");\n")
}

// cppInput names the runtime helper converting a Python argument.
func cppInput(t *abi.Type) string {
	switch t.Kind {
	case abi.String:
		return "string_arg"
	case abi.Boolean:
		return "bool_arg"
	case abi.Float:
		return "float_arg<" + t.C + ">"
	default:
		return "integer_arg<" + t.C + ">"
	}
}

// cppOutput converts a C result field to a Python object.
func cppOutput(t *abi.Type, field string) string {
	switch t.Kind {
	case abi.String:
		return "decode(" + field + ")"
	case abi.Boolean:
		return "py::bool_(" + field + " != 0)"
	case abi.Float:
		return "py::float_(" + field + ")"
	default:
		return "py::int_(" + field + ")"
	}
}
