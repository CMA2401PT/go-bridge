package emit

// holderSource implements opaque integer handles. No Go pointer crosses C.
// Each handle owns one Go root; structs and views will store *T in that root.
const holderSource = `// Code generated by go-bridge. DO NOT EDIT.
package main
/*
#include <stdint.h>
*/
import "C"
import (
"runtime"
"runtime/cgo"
"sync/atomic"
)
var bridgeRoots atomic.Int64
func bridgePin[T any](value T) C.uintptr_t {
    h := cgo.NewHandle(value)
    bridgeRoots.Add(1)
    return C.uintptr_t(h)
}
func bridgeStruct[T any](value T) C.uintptr_t { return bridgePin(&value) }
func bridgeGet[T any](handle C.uintptr_t) T {
    return cgo.Handle(handle).Value().(T)
}
func bridgePointer[T any](handle C.uintptr_t) T {
    if handle == 0 { var zero T; return zero }
    return bridgeGet[T](handle)
}
//export SBRelease
func SBRelease(handle C.uintptr_t) {
    if handle == 0 { return }
    cgo.Handle(handle).Delete()
    bridgeRoots.Add(-1)
}
//export SBHolderCount
func SBHolderCount() C.int64_t { return C.int64_t(bridgeRoots.Load()) }
//export SBCollect
func SBCollect() { runtime.GC() }
`
