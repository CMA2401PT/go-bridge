package emit

import (
	"fmt"
	"strings"

	"go-bridge/internal/abi"
)

// anyRuntime maps nil interfaces to handle 0 and stores any other value in a
// holder root as is. Assertions happen in the per-type exports below.
const anyRuntime = `// Code generated by go-bridge. DO NOT EDIT.
package main
/*
#include <stdint.h>
*/
import "C"
import "runtime/cgo"
func bridgeAny(handle C.uintptr_t) any {
    if handle == 0 { return nil }
    return cgo.Handle(handle).Value()
}
func bridgePinAny(value any) C.uintptr_t {
    if value == nil { return 0 }
    return bridgePin(value)
}
`

func goAnyConversion(b *strings.Builder, c *abi.AnyConversion) {
	t := c.Type
	goExport(b, c.Box, "input C."+t.C, "uintptr_t")
	fmt.Fprintf(b, "out = bridgePinAny(%s)\nreturn\n}\n", goInput(t, "input"))
	goExport(b, c.Assert, "handle C.uintptr_t", c.Result)
	fmt.Fprintf(b, "value, ok := bridgeAny(handle).(%s)\nif !ok {return}\nout.ok = 1\n", t.Go)
	goOutput(b, t, "out.value", "value")
	b.WriteString("return\n}\n")
}
