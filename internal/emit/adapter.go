package emit

import (
	"fmt"
	"strings"

	"go-bridge/internal/abi"
	"go-bridge/internal/pyapi"
)

// adapterPrelude declares the C types shared by every operation.
const adapterPrelude = `// Code generated by go-bridge. DO NOT EDIT.
package main

/*
#include <stdint.h>
#include <stddef.h>
#include <stdlib.h>
typedef struct { char *data; size_t size; } SBString;
`

// adapterRuntime copies strings across the boundary.
const adapterRuntime = `
// bridgeString copies value into C memory owned by the caller.
func bridgeString(value string) C.SBString {
	return C.SBString{data: C.CString(value), size: C.size_t(len(value))}
}

// bridgeInput copies a borrowed C buffer into a Go string.
func bridgeInput(value C.SBString) string {
	return string(unsafe.Slice((*byte)(unsafe.Pointer(value.data)), int(value.size)))
}
`

// goSource renders the cgo adapter: an internal initialization entry point and
// one exported function per target operation. Go panics propagate normally.
func goSource(p *abi.Package) string {
	var b strings.Builder
	b.WriteString(adapterPrelude)
	for _, op := range p.Operations {
		if len(op.Results) == 0 {
			continue
		}
		b.WriteString("typedef struct {\n")
		for i, r := range op.Results {
			fmt.Fprintf(&b, "%s r%d;\n", r.C, i)
		}
		fmt.Fprintf(&b, "} %s;\n", op.Result)
	}
	b.WriteString("*/\nimport \"C\"\n\nimport (\n\"unsafe\"\n\n")
	for _, imp := range p.Imports {
		fmt.Fprintf(&b, "%s %q\n", imp.Alias, imp.Path)
	}
	b.WriteString(")\n")
	b.WriteString(adapterRuntime)
	// An export is required even without API operations: cgo emits the header,
	// and C++ can enter Go to wait for target package initialization.
	fmt.Fprintf(&b, "\n//export %s\nfunc %s() {}\n", abi.InitSymbol, abi.InitSymbol)
	for _, op := range p.Operations {
		goOperation(&b, op)
	}
	for _, s := range p.Slices {
		goSlice(&b, s)
	}
	for _, c := range p.Classes {
		goClass(&b, c)
	}
	b.WriteString("\nfunc main() {}\n")
	return b.String()
}

func goOperation(b *strings.Builder, op *abi.Operation) {
	params := join(len(op.Params), func(i int) string { return fmt.Sprintf("a%d C.%s", i, op.Params[i].C) })
	fmt.Fprintf(b, "\n//export %s\nfunc %s(%s)", op.Symbol, op.Symbol, params)
	if len(op.Results) > 0 {
		fmt.Fprintf(b, " (out C.%s)", op.Result)
	}
	b.WriteString(" {\n")

	if len(op.Results) > 0 {
		b.WriteString(join(len(op.Results), func(i int) string { return fmt.Sprintf("r%d", i) }))
		b.WriteString(" := ")
	}
	offset := 0
	target := "api." + op.Python.Go.Name
	if op.Receiver != nil {
		offset = 1
		receiver := goInput(op.Receiver, "a0")
		if op.Receiver.Python.Shape == pyapi.StructObject {
			receiver = "bridgeGet[" + op.Receiver.Cell + "](a0)"
		}
		target = "(" + receiver + ")." + op.Python.Go.Name
	}
	args := join(len(op.Params)-offset, func(i int) string { return goInput(op.Params[i+offset], fmt.Sprintf("a%d", i+offset)) })
	fmt.Fprintf(b, "%s(%s)\n", target, args)
	for i, r := range op.Results {
		goOutput(b, r, fmt.Sprintf("out.r%d", i), fmt.Sprintf("r%d", i))
	}
	if len(op.Results) > 0 {
		b.WriteString("return\n")
	}
	b.WriteString("}\n")
}

// goInput converts a C argument to the Go parameter type.
func goInput(t *abi.Type, value string) string {
	var result string
	switch t.Kind {
	case abi.Handle:
		switch t.Python.Shape {
		case pyapi.StructObject:
			return "*bridgeGet[" + t.Cell + "](" + value + ")"
		case pyapi.PointerObject:
			result = "bridgePointer[" + t.Cell + "](" + value + ")"
		default:
			result = "bridgeGet[" + t.Cell + "](" + value + ")"
		}
	case abi.String:
		result = "bridgeInput(" + value + ")"
	case abi.Boolean:
		result = value + " != 0"
	default:
		return t.Go + "(" + value + ")"
	}
	if t.Python.Underlying != nil {
		return t.Go + "(" + result + ")"
	}
	return result
}

// goOutput stores a Go result into its C result field.
func goOutput(b *strings.Builder, t *abi.Type, field, value string) {
	switch t.Kind {
	case abi.Handle:
		switch t.Python.Shape {
		case pyapi.StructObject:
			fmt.Fprintf(b, "%s = bridgeStruct(%s)\n", field, value)
		case pyapi.PointerObject:
			fmt.Fprintf(b, "if (%s) != nil {%s = bridgePin((%s)(%s))}\n", value, field, t.Cell, value)
		default:
			fmt.Fprintf(b, "%s = bridgePin((%s)(%s))\n", field, t.Cell, value)
		}
	case abi.String:
		fmt.Fprintf(b, "%s = bridgeString(string(%s))\n", field, value)
	case abi.Boolean:
		fmt.Fprintf(b, "if %s {\n%s = 1\n}\n", value, field)
	default:
		fmt.Fprintf(b, "%s = C.%s(%s)\n", field, t.C, value)
	}
}
